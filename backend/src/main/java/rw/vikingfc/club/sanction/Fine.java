package rw.vikingfc.club.sanction;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import rw.vikingfc.club.attendance.AttendanceRecord;
import rw.vikingfc.club.common.entity.BaseEntity;
import rw.vikingfc.club.common.util.Money;
import rw.vikingfc.club.match.FootballMatch;
import rw.vikingfc.club.player.Player;
import rw.vikingfc.club.staff.StaffMember;
import rw.vikingfc.club.training.TrainingSession;

import java.math.BigDecimal;
import java.time.LocalDate;

@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "fines")
public class Fine extends BaseEntity {
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "player_id")
    private Player player;
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "staff_id")
    private StaffMember staff;
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 40)
    private FineType fineType;
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private FineSource sourceType;
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "training_session_id")
    private TrainingSession trainingSession;
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "attendance_record_id", unique = true)
    private AttendanceRecord attendanceRecord;
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "match_id")
    private FootballMatch match;
    @Column(nullable = false)
    private LocalDate fineDate;
    private Integer weekNumber;
    private Integer minutesLate;
    @Column(nullable = false)
    private boolean justified;
    @Column(nullable = false, precision = 14, scale = 0)
    private BigDecimal amount = Money.zero();
    @Column(nullable = false, precision = 14, scale = 0)
    private BigDecimal amountPaid = Money.zero();
    @Column(length = 500)
    private String reason;
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private FineStatus status = FineStatus.OUTSTANDING;
    @Column(length = 120)
    private String waivedBy;
    @Column(length = 400)
    private String waiveReason;
    @Column(nullable = false)
    private boolean autoGenerated;

    public BigDecimal balance() {
        return Money.nz(amount).subtract(Money.nz(amountPaid));
    }
}
