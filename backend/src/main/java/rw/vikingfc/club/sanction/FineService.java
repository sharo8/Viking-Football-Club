import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

@Service
@RequiredArgsConstructor
@Transactional
public class FineService {

    private final FineRepository fineRepository;
    private final FinePaymentRepository finePaymentRepository;
    private final PayDeductionRepository payDeductionRepository;
    private final AttendanceRecordRepository attendanceRecordRepository;
    private final PayrollInstalmentRepository instalmentRepository;
    private final SettingsService settingsService;
    private final NotificationService notificationService;
    private final AuditService auditService;
    private final Clock clock;

    public void ensureFromAttendance() {
        if (fineRepository.count() > 0) {
            return;
        }
        for (AttendanceRecord record : attendanceRecordRepository.findAll()) {
            sync(record, false);
        }
    }

    public void sync(AttendanceRecord record, boolean notify) {
        ClubSettings settings = settingsService.current();
        FinePolicy.Decision decision = FinePolicy.training(record.getStatus(), record.getMinutesLate(), record.isJustified(),
                settings.getTrainingLateMinutes(), settings.getTrainingLateFine(), settings.getTrainingAbsenceFine());
        Fine existing = fineRepository.findByAttendanceRecordId(record.getId()).orElse(null);
        if (!decision.fine()) {
            if (existing != null && existing.isAutoGenerated() && existing.getStatus() == FineStatus.OUTSTANDING) {
                fineRepository.delete(existing);
            }
            return;
        }
        if (existing != null) {
            if (existing.getStatus() == FineStatus.PAID || existing.getStatus() == FineStatus.WAIVED) {
                return;
            }
            existing.setFineType(decision.type());
            existing.setAmount(decision.amount());
            existing.setMinutesLate(record.getMinutesLate());
            existing.setJustified(record.isJustified());
            return;
        }
        Fine fine = new Fine();
        fine.setPlayer(record.getPlayer());
        fine.setFineType(decision.type());
        fine.setSourceType(FineSource.TRAINING);
        fine.setTrainingSession(record.getSession());
        fine.setAttendanceRecord(record);
        fine.setFineDate(record.getSession().getSessionDate());
        fine.setWeekNumber(record.getSession().getWeekNumber());
        fine.setMinutesLate(record.getMinutesLate());
        fine.setJustified(record.isJustified());
        fine.setAmount(decision.amount());
        fine.setAmountPaid(Money.zero());
        fine.setReason(decision.type() == FineType.TRAINING_ABSENCE
                ? "Unexcused absence (Rule 7)" : "Late arrival over " + settings.getTrainingLateMinutes() + " minutes (Rule 6)");
        fine.setStatus(FineStatus.OUTSTANDING);
        fine.setAutoGenerated(true);
        fineRepository.save(fine);
        if (notify) {
            notificationService.notifyRoles(List.of(Role.HEAD_COACH, Role.ASSISTANT_COACH, Role.GOALKEEPER_COACH),
                    "FINE", "Fine issued", record.getPlayer().getKnownAs() + " — " + fine.getAmount() + " RWF", "/fines");
        }
    }

    public Fine matchLate(rw.vikingfc.club.match.FootballMatch match, Player player, int minutesLate, boolean justified) {
        ClubSettings settings = settingsService.current();
        FinePolicy.Decision decision = FinePolicy.matchLate(minutesLate, justified, settings.getMatchLateMinutes(), settings.getMatchLateFine());
        List<Fine> existing = fineRepository.findByMatchIdAndPlayerIdAndFineType(match.getId(), player.getId(), FineType.MATCH_LATE);
        if (!decision.fine()) {
            existing.stream().filter(fine -> fine.getStatus() == FineStatus.OUTSTANDING).forEach(fineRepository::delete);
            return null;
        }
        if (!existing.isEmpty()) {
            return existing.get(0);
        }
        Fine fine = new Fine();
        fine.setPlayer(player);
        fine.setMatch(match);
        fine.setFineType(FineType.MATCH_LATE);
        fine.setSourceType(FineSource.MATCH);
        fine.setFineDate(LocalDate.now(clock));
        fine.setMinutesLate(minutesLate);
        fine.setJustified(justified);
        fine.setAmount(decision.amount());
        fine.setAmountPaid(Money.zero());
        fine.setReason("Late arrival to the match");
        fine.setStatus(FineStatus.OUTSTANDING);
        fine.setAutoGenerated(true);
        fine.setWeekNumber(rw.vikingfc.club.common.util.ClubDates.weekNumber(settings.getFirstTrainingMonday(), fine.getFineDate()));
        return fineRepository.save(fine);
    }

    @Transactional(readOnly = true)
    public Map<String, Object> summary() {
        List<Fine> fines = fineRepository.findAll();
        BigDecimal total = sum(fines, Fine::getAmount);
        BigDecimal absence = sum(fines.stream().filter(fine -> fine.getFineType() == FineType.TRAINING_ABSENCE).toList(), Fine::getAmount);
        BigDecimal late = sum(fines.stream().filter(fine -> fine.getFineType() == FineType.TRAINING_LATE || fine.getFineType() == FineType.MATCH_LATE).toList(), Fine::getAmount);
        BigDecimal collected = sum(fines, Fine::getAmountPaid);
        BigDecimal outstanding = fines.stream().filter(fine -> fine.getStatus() != FineStatus.WAIVED)
                .map(Fine::balance).reduce(Money.zero(), BigDecimal::add);
        long players = fines.stream().map(fine -> fine.getPlayer().getId()).distinct().count();
        Map<String, Object> body = new LinkedHashMap<>();
        body.put("totalFinesDue", total);
        body.put("absenceFines", absence);
        body.put("lateFines", late);
        body.put("collected", collected);
        body.put("outstanding", outstanding);
        body.put("playersFined", players);
        body.put("fineCount", fines.size());
        return body;
    }

    public Fine pay(Long id, BigDecimal amount, PayMethod method, String reference) {
        Fine fine = require(id);
        BigDecimal payment = Money.nz(amount);
        if (payment.signum() <= 0 || payment.compareTo(fine.balance()) > 0) {
            throw BusinessException.conflict("Fine payment must be greater than zero and not above the balance");
        }
        fine.setAmountPaid(Money.nz(fine.getAmountPaid()).add(payment));
        fine.setStatus(fine.balance().signum() == 0 ? FineStatus.PAID : FineStatus.PARTIALLY_PAID);
        FinePayment row = new FinePayment();
        row.setFine(fine);
        row.setAmount(payment);
        row.setMethod(method);
        row.setReferenceNo(reference);
        row.setPaidAt(Instant.now(clock));
        row.setReceivedBy(SecurityUtils.email());
        finePaymentRepository.save(row);
        auditService.record("PAY", "Fine", id, null, payment, null);
        return fine;
    }

    public Fine waive(Long id, String reason) {
        Fine fine = require(id);
        if (reason == null || reason.isBlank()) {
            throw BusinessException.unprocessable("A waiver reason is required");
        }
        fine.setStatus(FineStatus.WAIVED);
        fine.setWaivedBy(SecurityUtils.email());
        fine.setWaiveReason(reason);
        auditService.record("WAIVE", "Fine", id, null, reason, null);
        return fine;
    }

    public Map<String, Object> deductFromPay(Long fineId) {
        Fine fine = require(fineId);
        if (fine.balance().signum() <= 0) {
            throw BusinessException.conflict("This fine has no outstanding balance");
        }
        PayrollInstalment instalment = instalmentRepository.findByPlayerIdOrderByDueDateAsc(fine.getPlayer().getId()).stream()
                .filter(row -> row.getStatus() != InstalmentStatus.PAID && row.cashRemaining().signum() > 0)
                .findFirst()
                .orElseThrow(() -> BusinessException.conflict("No open pay instalment to deduct from"));
        BigDecimal amount = fine.balance().min(instalment.cashRemaining());
        instalment.setAmountDeducted(Money.nz(instalment.getAmountDeducted()).add(amount));
        if (instalment.cashRemaining().signum() <= 0) {
            instalment.setStatus(InstalmentStatus.PAID);
        }
        fine.setAmountPaid(Money.nz(fine.getAmountPaid()).add(amount));
        fine.setStatus(fine.balance().signum() == 0 ? FineStatus.PAID : FineStatus.PARTIALLY_PAID);
        PayDeduction deduction = new PayDeduction();
        deduction.setFine(fine);
        deduction.setInstalment(instalment);
        deduction.setAmount(amount);
        deduction.setReason("Deducted from " + instalment.getKind());
        payDeductionRepository.save(deduction);
        FinePayment payment = new FinePayment();
        payment.setFine(fine);
        payment.setAmount(amount);
        payment.setMethod(PayMethod.DEDUCTION);
        payment.setPaidAt(Instant.now(clock));
        payment.setReceivedBy(SecurityUtils.email());
        payment.setReferenceNo("DEDUCT-" + instalment.getId());
        finePaymentRepository.save(payment);
        auditService.record("DEDUCT", "Fine", fineId, null, amount, null);
        return Map.of("fineId", fineId, "deducted", amount, "instalmentId", instalment.getId(), "fineStatus", fine.getStatus());
    }

    @Transactional(readOnly = true)
    public List<Map<String, Object>> byWeek() {
        Map<Integer, BigDecimal> weeks = new LinkedHashMap<>();
        for (int week = 1; week <= 20; week++) {
            weeks.put(week, Money.zero());
        }
        for (Fine fine : fineRepository.findAll()) {
            if (fine.getWeekNumber() != null && fine.getWeekNumber() >= 1 && fine.getWeekNumber() <= 20) {
                weeks.merge(fine.getWeekNumber(), fine.getAmount(), BigDecimal::add);
            }
        }
        List<Map<String, Object>> rows = new ArrayList<>();
        weeks.forEach((week, amount) -> rows.add(Map.of("week", week, "amount", amount)));
        return rows;
    }

    @Transactional(readOnly = true)
    public List<Map<String, Object>> ledger() {
        return fineRepository.findAll().stream()
                .sorted(Comparator.comparing(Fine::getFineDate).thenComparing(Fine::getId))
                .map(this::row)
                .toList();
    }

    private Map<String, Object> row(Fine fine) {
        Map<String, Object> row = new LinkedHashMap<>();
        row.put("id", fine.getId());
        row.put("player", fine.getPlayer() == null ? null : fine.getPlayer().getFullName());
        row.put("type", fine.getFineType());
        row.put("date", fine.getFineDate());
        row.put("week", fine.getWeekNumber());
        row.put("amount", fine.getAmount());
        row.put("paid", fine.getAmountPaid());
        row.put("balance", fine.balance());
        row.put("status", fine.getStatus());
        row.put("reason", fine.getReason());
        return row;
    }

    private Fine require(Long id) {
        return fineRepository.findById(id).orElseThrow(() -> NotFoundException.of("Fine", id));
    }

    private BigDecimal sum(List<Fine> fines, java.util.function.Function<Fine, BigDecimal> getter) {
        return fines.stream().map(getter).map(Money::nz).reduce(Money.zero(), BigDecimal::add);
    }
}
